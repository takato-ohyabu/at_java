package AT_Unit1.Question4;

public class A {
    private int xx;
    public A() {
        xx = 1;
    }
    public A(int x) {
        xx = x;
    }
    public void addX(int x) {
        xx += x;
    }
    public void multX(int x) {
        xx *= x;
    }
    public int getXX() {
        return xx;
    }
}
